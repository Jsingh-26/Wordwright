"""Write eval/results/REPORT.md (docs/EVAL.md → Output).

The report is the evidence behind every entry in models/models.json: quality
scores per model per action, automatic-check failure rates, measured speed per
tier, and how well the judges agreed with the maintainer's spot check. It ends
with the suggested catalog speed ranges and one default per tier.

    python eval/report.py
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import common

SPEED_WIDEN = 0.15  # catalog ranges are widened by 15% (docs/EVAL.md → Part B)


def read_json(path: Path) -> dict | None:
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def read_csv(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with path.open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def catalog_by_id() -> dict[str, dict]:
    return {model["id"]: model for model in common.catalog_models(status=None)}


def failure_rates(summary: list[dict]) -> dict[str, dict]:
    """Per model: how many cases failed each automatic check."""
    rates: dict[str, dict] = {}

    for row in summary:
        bucket = rates.setdefault(row["model"], {"cases": 0, "failed": 0, "checks": {}})
        bucket["cases"] += 1
        failures = [name for name in row.get("failed_checks", "").split("|") if name]
        if failures:
            bucket["failed"] += 1
        for name in failures:
            bucket["checks"][name] = bucket["checks"].get(name, 0) + 1

    return rates


def speed_ranges(speed: list[dict]) -> dict[str, dict]:
    """min-max prompt/gen tokens per second per tier, widened by 15%."""
    tiers: dict[str, dict[str, list[float]]] = {}

    for row in speed:
        tier = (row.get("tier") or "").strip()
        if not tier:
            continue
        bucket = tiers.setdefault(tier, {"promptTps": [], "genTps": [], "loadSeconds": [], "machines": []})
        for key, column in (("promptTps", "promptTps"), ("genTps", "genTps"), ("loadSeconds", "loadSeconds")):
            try:
                bucket[key].append(float(row[column]))
            except (KeyError, TypeError, ValueError):
                pass
        machine = (row.get("machine") or "").strip()
        if machine and machine not in bucket["machines"]:
            bucket["machines"].append(machine)

    ranges = {}
    for tier, bucket in tiers.items():
        entry: dict = {"machines": len(bucket["machines"]), "provisional": len(bucket["machines"]) < 2}
        for key in ("promptTps", "genTps"):
            if bucket[key]:
                low, high = min(bucket[key]), max(bucket[key])
                entry[key] = [round(low * (1 - SPEED_WIDEN), 1), round(high * (1 + SPEED_WIDEN), 1)]
        if bucket["loadSeconds"]:
            entry["loadSeconds"] = round(max(bucket["loadSeconds"]), 1)
        ranges[tier] = entry

    return ranges


def parameter_count(model: dict) -> float:
    """The size in billions, for the equal-score tie-break ("0.8B" -> 0.8).

    Sorting the strings would put "14B" before "2B"; the smaller model is the
    one that should win a tie, so compare the numbers.
    """
    text = str(model.get("parameters", "")).strip().lower().rstrip("b").strip()
    try:
        return float(text)
    except ValueError:
        return float("inf")


def pick_defaults(scores: dict, catalog: dict[str, dict]) -> dict[str, tuple[str, str]]:
    """The best-scoring model that fits each tier, with one sentence of reasoning."""
    tiers = sorted({tier for model in catalog.values() for tier in model.get("tiers", [])})
    defaults: dict[str, tuple[str, str]] = {}

    for tier in tiers:
        fitting = [
            (model_id, data["evalScores"]["overall"])
            for model_id, data in scores["models"].items()
            if model_id in catalog and tier in catalog[model_id].get("tiers", [])
        ]
        if not fitting:
            continue

        fitting.sort(key=lambda pair: (-pair[1], parameter_count(catalog[pair[0]])))
        model_id, best = fitting[0]
        runner_up = fitting[1][1] if len(fitting) > 1 else None

        if runner_up is None or best - runner_up > 0.1:
            reason = f"the highest overall score ({best:.2f}) among the models that fit this tier"
        else:
            reason = (
                f"scored {best:.2f}, within 0.1 of {fitting[1][0]} ({runner_up:.2f}), "
                "so the smaller model is preferred for speed"
            )

        defaults[tier] = (model_id, reason)

    return defaults


def build_lines(scores: dict, rates: dict, ranges: dict, defaults: dict, spotcheck: dict | None) -> list[str]:
    catalog = catalog_by_id()
    lines = [
        "# Model evaluation report",
        "",
        "Generated by `eval/report.py`. This is the evidence behind `models/models.json`.",
        "",
        "## Quality (judges, 1-5, capped at 2 when an automatic check failed)",
        "",
    ]

    models = sorted(scores["models"])
    actions = common.ACTIONS
    lines.append("| Model | " + " | ".join(actions) + " | overall |")
    lines.append("|---" * (len(actions) + 2) + "|")

    for model_id in models:
        row = scores["models"][model_id]["evalScores"]
        cells = [f"{row[action]:.2f}" if action in row else "-" for action in actions]
        lines.append(f"| {model_id} | " + " | ".join(cells) + f" | **{row['overall']:.2f}** |")

    lines += ["", "## Automatic checks", ""]
    lines.append("| Model | cases | failed any | " + " | ".join(sorted({name for rate in rates.values() for name in rate["checks"]})) + " |")
    lines.append("|---" * 3 + "|---" * len({name for rate in rates.values() for name in rate["checks"]}) + "|")

    for model_id in sorted(rates):
        rate = rates[model_id]
        checks = sorted({name for other in rates.values() for name in other["checks"]})
        cells = [str(rate["checks"].get(name, 0)) for name in checks]
        lines.append(f"| {model_id} | {rate['cases']} | {rate['failed']} | " + " | ".join(cells) + " |")

    lines += ["", "## Speed", ""]
    if ranges:
        lines.append("| Tier | machines | prompt tok/s | generation tok/s | load s | provisional |")
        lines.append("|---|---|---|---|---|---|")
        for tier, entry in sorted(ranges.items()):
            prompt = entry.get("promptTps", ["-", "-"])
            gen = entry.get("genTps", ["-", "-"])
            lines.append(
                f"| {tier} | {entry['machines']} | {prompt[0]}-{prompt[1]} | {gen[0]}-{gen[1]} | "
                f"{entry.get('loadSeconds', '-')} | {'yes' if entry['provisional'] else 'no'} |"
            )
        lines += ["", "Suggested `speed` entries (observed min-max, widened by 15%):", "", "```json"]
        lines.append(json.dumps(ranges, indent=2))
        lines.append("```")
    else:
        lines.append("No `eval/results/speed.csv` rows yet.")

    lines += ["", "## Judge and human agreement", ""]
    if spotcheck:
        lines.append(
            f"Spot check: {spotcheck['compared']} of {spotcheck['checked']} outputs compared, "
            f"**{spotcheck['caseAgreement']:.0%} of cases within ±{spotcheck['tolerance']}** "
            f"(target {spotcheck['target']:.0%})."
        )
        lines.append("")
        for criterion, share in spotcheck["criterionAgreement"].items():
            lines.append(f"- {criterion.replace('_', ' ')}: {share:.0%}")
    else:
        lines.append("No `eval/results/spotcheck.json` yet; run `python eval/spotcheck.py`.")

    lines += ["", "## Default per tier", ""]
    if defaults:
        for tier, (model_id, reason) in sorted(defaults.items()):
            lines.append(f"- **{tier}**: `{model_id}` — {reason}.")
    else:
        lines.append("Not enough scored models to choose a default.")

    lines += [
        "",
        "Only after this report is reviewed should `status` move from `candidate` to `approved`,",
        "and `evalScores` and measured speeds be written into `models/models.json` (P9.4).",
        "",
    ]

    return lines


def main() -> int:
    scores = read_json(common.RESULTS_DIR / "scores.json")
    if scores is None:
        raise SystemExit("no eval/results/scores.json; run eval/judge.py first")

    summary = read_csv(common.RESULTS_DIR / "summary.csv")
    speed = read_csv(common.RESULTS_DIR / "speed.csv")
    spotcheck = read_json(common.RESULTS_DIR / "spotcheck.json")

    rates = failure_rates(summary)
    ranges = speed_ranges(speed)
    defaults = pick_defaults(scores, catalog_by_id())

    lines = build_lines(scores, rates, ranges, defaults, spotcheck)

    path = common.RESULTS_DIR / "REPORT.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {path}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
